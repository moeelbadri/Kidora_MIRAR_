        foreach ($scenarios as $topic => $rows) {
            foreach ($rows as $i => $s) {
                $choices = array_map(fn($c) => ['l' => $c[0], 'g' => (bool)$c[1], 'r' => $c[2]], $s[1]);
                $stmt->execute([$topic, $s[0], json_encode($choices, JSON_UNESCAPED_UNICODE), $i + 1]);
            }
        }
    }
